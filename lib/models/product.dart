class Product {
  final int id;
  final String name;
  final String description;
  final double price;
  final String image;
  final double rating;
  final int timeMinutes;
  final bool isSpicy;

  Product({
    required this.id,
    required this.name,
    required this.description,
    required this.price,
    required this.image,
    required this.rating,
    required this.timeMinutes,
    required this.isSpicy,
  });
}
